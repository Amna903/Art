// Parses public/map/Group 1.svg — a Figma export where each country's
// artwork pieces are wrapped in a named <g id="CountryName">...</g> — and
// emits lib/data/africa-map-regions.ts: a static map of country slug to the
// exact combined path data for that country's pieces, in the artwork's own
// viewBox coordinate space (0..7308, 0..7894). This gives pixel-accurate
// hit-regions instead of the real-geography + correction-warp approximation.
//
// Run with: node scripts/extract-map-groups.mjs

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SVG_PATH = path.join(__dirname, "..", "public", "map", "Group 1.svg");
const OUT_PATH = path.join(__dirname, "..", "lib", "data", "africa-map-regions.ts");

function decodeXmlEntities(s) {
  // Numeric entities here are UTF-8 bytes split across multiple &#NNN;
  // refs (Figma's export quirk) — collect raw bytes, then decode as UTF-8.
  const bytes = [];
  let i = 0;
  while (i < s.length) {
    const m = /^&#(\d+);/.exec(s.slice(i));
    if (m) {
      bytes.push(parseInt(m[1], 10));
      i += m[0].length;
    } else {
      const code = s.codePointAt(i);
      // Encode this JS char as UTF-8 bytes too, so mixed content decodes correctly.
      const buf = Buffer.from(String.fromCodePoint(code), "utf8");
      for (const b of buf) bytes.push(b);
      i += String.fromCodePoint(code).length;
    }
  }
  return Buffer.from(bytes).toString("utf8");
}

