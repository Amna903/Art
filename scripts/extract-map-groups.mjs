const svg = fs.readFileSync(SVG_PATH, "utf8");
const lines = svg.split("\n");

const stack = [];
/** @type {Map<string, string[]>} raw layer name -> path d[] */
const byRawName = new Map();

for (const line of lines) {
  const gOpen = line.match(/<g id="([^"]*)">/);
  if (gOpen) {
    const raw = decodeXmlEntities(gOpen[1]).trim();
    stack.push(raw);
    continue;
  }
  if (line.includes("</g>")) {
    stack.pop();
    continue;
  }
  const p = line.match(/<path[^>]*\bd="([^"]+)"/);
  if (p && stack.length > 0) {
    const current = stack[stack.length - 1];
    if (current !== "Group 1") {
      if (!byRawName.has(current)) byRawName.set(current, []);
      byRawName.get(current).push(p[1]);
    }
  }
}

console.log(`Found ${byRawName.size} named group(s) in the SVG:`);
for (const [name, paths] of byRawName) {
  const mapped = NAME_TO_SLUG[name];
  console.log(`  "${name}" -> ${mapped ?? "??? (unmapped, add to NAME_TO_SLUG)"} (${paths.length} path${paths.length === 1 ? "" : "s"})`);
}

/** @type {Map<string, string[]>} slug -> path d[] (merged across raw names) */
const bySlug = new Map();
for (const [name, paths] of byRawName) {
  const slug = NAME_TO_SLUG[name];
  if (!slug) continue;
  if (!bySlug.has(slug)) bySlug.set(slug, []);
  bySlug.get(slug).push(...paths);
}

const viewBoxMatch = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
const vbW = parseFloat(viewBoxMatch[1]);
const vbH = parseFloat(viewBoxMatch[2]);

const entries = [...bySlug.entries()].sort(([a], [b]) => a.localeCompare(b));
const lines_out = [];
lines_out.push("// AUTO-GENERATED by scripts/extract-map-groups.mjs — do not hand-edit.");
lines_out.push('// Regenerate after updating public/map/"Group 1.svg" labels: node scripts/extract-map-groups.mjs');
lines_out.push("//");
lines_out.push("// Exact per-country path data (combined multi-subpath \"d\" strings) parsed");
lines_out.push('// from the named <g id="Country"> layers in the Figma export. Coordinates');
lines_out.push(`// are in the artwork's native viewBox space (0..${vbW}, 0..${vbH}).`);
lines_out.push("");
lines_out.push(`export const MAP_REGIONS_VIEWBOX: [number, number] = [${vbW}, ${vbH}];`);
lines_out.push("");
lines_out.push("export const MAP_REGIONS: Record<string, string> = {");
for (const [slug, paths] of entries) {
  const combined = paths.join(" ");
  lines_out.push(`  "${slug}": "${combined}",`);
}
lines_out.push("};");
lines_out.push("");

fs.writeFileSync(OUT_PATH, lines_out.join("\n"));
console.log(`\nWrote ${entries.length} countries to ${OUT_PATH}`);
const covered = new Set(entries.map(([slug]) => slug));
console.log(`Covered slugs: ${[...covered].sort().join(", ")}`);
